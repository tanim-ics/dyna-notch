#!/usr/bin/env python3
"""Builds Sources/DynaNotch/Views/Settings/SettingsIndex.swift: every settings row with a literal title, the page it
lives on, its icon and its grey line, so the sidebar search and the command palette can jump straight to an option.

Run after adding or renaming a settings row; `scripts/check.sh` fails when the file is out of date (--check)."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Sources/DynaNotch/Views/Settings")
OUT = os.path.join(DIR, "SettingsIndex.swift")
ROWS = r"(?:SettingToggle|SettingRow|SettingValueRow|SliderRow|IntSliderRow|PermissionRow|StepperRow|SettingStackedRow|ShortcutRow|ShapeChoiceRow)"
STR = r'"((?:[^"\\]|\\.)*)"'


def structs(text):
    """(name, body) for each top-level `struct X` (body = text up to the next top-level declaration)."""
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"^(?:private |fileprivate )?struct (\w+)", text, re.M)]
    for i, (pos, name) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        yield name, text[pos:end]


def main():
    bodies = {}
    for f in sorted(os.listdir(DIR)):
        if f.endswith(".swift") and f != "SettingsIndex.swift":
            for name, body in structs(open(os.path.join(DIR, f)).read()):
                bodies[name] = body
    page_of = {}
    for name, body in bodies.items():
        m = re.search(r"SettingsPageView\(page: \.(\w+)\)", body)
        if m:
            page_of[name] = m.group(1)
    # Helper views take the page of the pane that uses them (a few levels deep).
    for _ in range(4):
        for name, body in bodies.items():
            if name in page_of:
                continue
            users = {page_of[o] for o, ob in bodies.items() if o in page_of and re.search(r"\b%s\b\s*\(" % name, ob)}
            if len(users) == 1:
                page_of[name] = users.pop()
    entries, seen = [], set()
    for name, body in bodies.items():
        page = page_of.get(name)
        if not page:
            continue
        for m in re.finditer(ROWS + r"\(", body):
            call = body[m.end():m.end() + 600]
            t = re.search(r"title: " + STR, call)
            if not t or "\\(" in t.group(1):
                continue
            # The title must belong to this call, not a later one.
            nxt = re.search(ROWS + r"\(", call)
            if nxt and nxt.start() < t.start():
                continue
            d = re.search(r"detail: " + STR, call)
            s = re.search(r"symbol: " + STR, call)
            c = re.search(r"color: \.(\w+)", call)
            detail = d.group(1) if d and "\\(" not in d.group(1) else ""
            key = (page, t.group(1))
            if key in seen:
                continue
            seen.add(key)
            entries.append((page, t.group(1), detail, s.group(1) if s else "gearshape", c.group(1) if c else "gray"))
    entries.sort(key=lambda e: (e[0], e[1].lower()))
    lines = ["// Generated by scripts/gen_settings_index.py — do not edit.", "import SwiftUI", "",
             "extension SettingsOption {", "    static let all: [SettingsOption] = ["]
    for page, title, detail, symbol, color in entries:
        lines.append('        SettingsOption(page: .%s, title: "%s", detail: "%s", symbol: "%s", color: .%s),'
                     % (page, title, detail, symbol, color))
    lines += ["    ]", "}", ""]
    out = "\n".join(lines)
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != out:
            print("SettingsIndex.swift is out of date: run scripts/gen_settings_index.py")
            sys.exit(1)
        print("settings index: %d options, up to date" % len(entries))
        return
    open(OUT, "w").write(out)
    print("settings index: %d options" % len(entries))


main()
