import AppKit
import Combine
import CoreGraphics
import CryptoKit
import Foundation
import os
import DynaNotchCore

/// Clipboard history: polls NSPasteboard, keeps `ClipboardHistory`, persists it.
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published private(set) var history = ClipboardHistory()

    private let logger = Logger(subsystem: "com.tanim.dynanotch", category: "clipboard")
    private let pasteboard = NSPasteboard.general
    private let imageCache = NSCache<NSString, NSImage>()
    private let ioQueue = DispatchQueue(label: "com.tanim.dynanotch.clipboard.io", qos: .utility)

    private var started = false
    private var pollTimer: AnyCancellable?
    private var autoClearTimer: AnyCancellable?
    private var limitObserver: AnyCancellable?
    private var saveObserver: AnyCancellable?
    private let saveRequests = PassthroughSubject<Void, Never>()
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var pollObserver: AnyCancellable?
    /// Copy twice to open: when the previous outside copy happened.
    private var lastExternalCopyAt: Date?
    /// Time window for "⌘C ⌘C" (settings.copyTwiceToOpen).
    static let copyTwiceWindow: TimeInterval = 0.6

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private static var supportDirectory: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent("Library/Application Support")
        return base.appendingPathComponent("DynaNotch", isDirectory: true)
    }

    private static var clipsDirectory: URL {
        supportDirectory.appendingPathComponent("Clips", isDirectory: true)
    }

    private static var historyFile: URL {
        supportDirectory.appendingPathComponent("clipboard.json")
    }

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
        imageCache.countLimit = 40
        loadHistory()

        saveObserver = saveRequests
            .debounce(for: .seconds(1), scheduler: DispatchQueue.main)
            .sink { [weak self] in self?.saveHistory() }

        limitObserver = AppSettings.shared.$clipboardLimit
            .removeDuplicates()
            .receive(on: DispatchQueue.main)
            .sink { [weak self] limit in self?.applyLimit(limit) }
    }

    // MARK: Public API

    func start() {
        UserPresence.shared.start()
        guard !started else { return }
        started = true
        // Do not import whatever was on the clipboard before we started.
        lastChangeCount = pasteboard.changeCount
        // Copy twice to open needs a finer clock to tell two quick copies apart.
        pollObserver = AppSettings.shared.$copyTwiceToOpen
            .removeDuplicates()
            .receive(on: DispatchQueue.main)
            .sink { [weak self] fast in self?.schedulePolling(fast: fast) }
        autoClearTimer = Timer.publish(every: 60, tolerance: 5, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in self?.autoClear() }
        autoClear()
    }

    func stop() {
        guard started else { return }
        started = false
        pollObserver = nil
        pollTimer?.cancel()
        pollTimer = nil
        autoClearTimer?.cancel()
        autoClearTimer = nil
    }

    /// "Paste as Plain Text" shortcut: re-writes the current pasteboard as a plain string (no fonts, colours or
    /// links), then sends ⌘V to the frontmost app (needs Accessibility; without it the plain text is just copied).
    func pasteCurrentAsPlainText() {
        var text = pasteboard.string(forType: .string)
        // Rich text only (some apps put no plain string): flatten RTF / RTFD / HTML.
        if text == nil {
            let rich: [(NSPasteboard.PasteboardType, NSAttributedString.DocumentType)] = [
                (.rtf, .rtf), (.rtfd, .rtfd), (.html, .html),
            ]
            for (type, docType) in rich {
                guard let data = pasteboard.data(forType: type),
                      let attributed = try? NSAttributedString(data: data, options: [.documentType: docType],
                                                               documentAttributes: nil) else { continue }
                text = attributed.string
                break
            }
        }
        if text == nil,
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            text = urls.map(\.path).joined(separator: "\n")
        }
        guard let plain = text, !plain.isEmpty else {
            logger.info("paste as plain text: nothing textual on the clipboard")
            return
        }
        pasteboard.clearContents()
        pasteboard.setString(plain, forType: .string)
        markOwnChange()
        guard Permissions.accessibilityGranted else {
            logger.notice("paste as plain text: no Accessibility, plain text left on the clipboard")
            return
        }
        // Give the user a moment to release the shortcut's modifiers.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) {
            ClipboardService.postCommandV()
        }
    }

    /// "Clean link" on a clipboard row (settings.offerCleanCopy): copies the link without tracking parameters;
    /// the original stays in the history as copied.
    @discardableResult
    func copyCleanLink(_ item: ClipItem) -> Bool {
        let cleaned = LinkCleaner.clean(item.text)
        guard item.kind == .link, cleaned != item.text else { return false }
        pasteboard.clearContents()
        pasteboard.setString(cleaned, forType: .string)
        // Not recorded as a new row: the list would jump; the original row shows "Clean copy" instead.
        markOwnChange()
        return true
    }

    /// True when the row should offer a "Clean link" button.
    func offersCleanCopy(for item: ClipItem) -> Bool {
        AppSettings.shared.offerCleanCopy && item.kind == .link && LinkCleaner.clean(item.text) != item.text
    }

    func copy(_ item: ClipItem) {
        write(item, plainText: false)
    }

    func paste(_ item: ClipItem, plainText: Bool) {
        write(item, plainText: plainText)
        guard Permissions.accessibilityGranted, AppSettings.shared.pasteOnClick else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
            ClipboardService.postCommandV()
        }
    }

    func remove(_ item: ClipItem) {
        var h = history
        guard let removed = h.remove(id: item.id) else { return }
        history = h
        deleteImageFiles(of: [removed])
        scheduleSave()
    }

    func togglePin(_ item: ClipItem) {
        var h = history
        h.togglePin(id: item.id)
        history = h
        scheduleSave()
    }

    func clear() {
        var h = history
        let removed = h.clear(keepPinned: true)
        history = h
        deleteImageFiles(of: removed)
        scheduleSave()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let file = item.imageFile, !file.isEmpty else { return nil }
        if let cached = imageCache.object(forKey: file as NSString) { return cached }
        let url = ClipboardService.clipsDirectory.appendingPathComponent(file)
        guard let image = NSImage(contentsOf: url) else { return nil }
        imageCache.setObject(image, forKey: file as NSString)
        return image
    }

    // MARK: Polling (main queue)

    private func schedulePolling(fast: Bool) {
        pollTimer?.cancel()
        // macOS has no pasteboard-change notification, so this polls; the tolerance lets the system wake us together
        // with the Caps Lock poll instead of separately.
        pollTimer = Timer.publish(every: fast ? 0.15 : 0.5, tolerance: fast ? 0.05 : 0.25, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in self?.poll() }
    }

    private func poll() {
        guard !UserPresence.shared.isAway else { return }   // locked / display asleep: nothing is being copied
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        let delta = count - lastChangeCount
        lastChangeCount = count
        if let own = ownChangeCount, own == count { return }
        detectCopyTwice(changes: delta)
        capture()
    }

    /// ⌘C ⌘C within `copyTwiceWindow` opens the Clipboard tab (two changes seen in one poll count too).
    private func detectCopyTwice(changes: Int) {
        guard AppSettings.shared.copyTwiceToOpen else { return }
        let now = Date()
        let quick = lastExternalCopyAt.map { now.timeIntervalSince($0) <= ClipboardService.copyTwiceWindow } ?? false
        if changes >= 2 || quick {
            lastExternalCopyAt = nil
            logger.info("copy twice → open Clipboard")
            DispatchQueue.main.async { AppActions.shared.perform(.clipboard) }
        } else {
            lastExternalCopyAt = now
        }
    }

    private func capture() {
        let types = (pasteboard.types ?? []).map(\.rawValue)
        if types.contains(where: { ClipboardService.ignoredTypes.contains($0) }) { return }
        let frontmost = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontmost?.bundleIdentifier, ClipboardService.ignoredApps().contains(bundleID.lowercased()) {
            return
        }
        let sourceApp = frontmost?.localizedName
        let now = Date()

        // File URLs first: Finder also puts the file name on the pasteboard as a string.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let text = urls.map(\.path).joined(separator: "\n")
            add(ClipItem(kind: .file, text: text, date: now, sourceApp: sourceApp))
            return
        }

        if let string = pasteboard.string(forType: .string) {
            guard !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            var text = string
            let kind = ClipClassifier.kind(for: text)
            // Offer a clean copy instead (row button): keep the link exactly as copied.
            if kind == .link, AppSettings.shared.cleanLinks, !AppSettings.shared.offerCleanCopy {
                let cleaned = LinkCleaner.clean(text)
                if cleaned != text {
                    text = cleaned
                    pasteboard.clearContents()
                    pasteboard.setString(cleaned, forType: .string)
                    markOwnChange()
                }
            }
            add(ClipItem(kind: kind, text: text, date: now, sourceApp: sourceApp))
            return
        }

        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            captureImage(data: data, sourceApp: sourceApp, date: now)
        }
    }

    private func captureImage(data: Data, sourceApp: String?, date: Date) {
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        if let existing = history.items.first(where: { $0.kind == .image && $0.text == hash }) {
            // Same image again: just move it to the top, no new file.
            add(ClipItem(kind: .image, text: hash, date: date, sourceApp: sourceApp, imageFile: existing.imageFile))
            return
        }
        guard let png = ClipboardService.pngData(from: data) else { return }
        let fileName = UUID().uuidString + ".png"
        let url = ClipboardService.clipsDirectory.appendingPathComponent(fileName)
        do {
            try FileManager.default.createDirectory(at: ClipboardService.clipsDirectory, withIntermediateDirectories: true)
            try png.write(to: url, options: .atomic)
        } catch {
            logger.error("could not save clip image: \(error.localizedDescription, privacy: .public)")
            return
        }
        add(ClipItem(kind: .image, text: hash, date: date, sourceApp: sourceApp, imageFile: fileName))
    }

    private func add(_ item: ClipItem, sound: Bool = true) {
        var h = history
        h.limit = AppSettings.shared.clipboardLimit
        let evicted = h.add(item)
        history = h
        deleteImageFiles(of: evicted)
        scheduleSave()
        if sound, AppSettings.shared.clipboardCaptureSound {
            ClipboardService.captureSound?.stop()
            ClipboardService.captureSound?.play()
        }
    }

    /// Short system sound for `settings.clipboardCaptureSound` (only clips this service records play it).
    private static let captureSound: NSSound? = {
        let sound = NSSound(named: NSSound.Name("Pop")) ?? NSSound(named: NSSound.Name("Tink"))
        sound?.volume = 0.6
        return sound
    }()

    /// Settings › Clipboard › Ignored apps: comma / newline separated bundle ids (case-insensitive).
    private static func ignoredApps() -> Set<String> {
        let raw = AppSettings.shared.clipboardIgnoredApps
        let ids = raw.split(whereSeparator: { $0 == "," || $0.isNewline || $0 == " " })
            .map { $0.trimmingCharacters(in: .whitespaces).lowercased() }
            .filter { !$0.isEmpty }
        return Set(ids)
    }

    /// `clipboardAutoClearMinutes` > 0: drops unpinned items older than that.
    private func autoClear() {
        let minutes = AppSettings.shared.clipboardAutoClearMinutes
        guard minutes > 0 else { return }
        let cutoff = Date().addingTimeInterval(-TimeInterval(minutes) * 60)
        let stale = history.items.filter { !$0.pinned && $0.date < cutoff }
        guard !stale.isEmpty else { return }
        var h = history
        var removed: [ClipItem] = []
        for item in stale {
            if let gone = h.remove(id: item.id) { removed.append(gone) }
        }
        history = h
        deleteImageFiles(of: removed)
        scheduleSave()
    }

    private func applyLimit(_ limit: Int) {
        var h = history
        h.limit = limit
        var evicted: [ClipItem] = []
        let cap = max(1, limit)
        while h.items.count > cap, let victim = h.items.last(where: { !$0.pinned }) {
            if let removed = h.remove(id: victim.id) { evicted.append(removed) } else { break }
        }
        guard h != history else { return }
        history = h
        deleteImageFiles(of: evicted)
        scheduleSave()
    }

    // MARK: Writing to the pasteboard

    private func write(_ item: ClipItem, plainText: Bool) {
        pasteboard.clearContents()
        switch item.kind {
        case .image:
            if !plainText, let image = image(for: item) {
                pasteboard.writeObjects([image])
            } else if let file = item.imageFile {
                pasteboard.setString(ClipboardService.clipsDirectory.appendingPathComponent(file).path, forType: .string)
            }
        case .file:
            let paths = item.text.split(separator: "\n").map(String.init).filter { !$0.isEmpty }
            if plainText {
                pasteboard.setString(item.text, forType: .string)
            } else {
                let urls = paths.map { URL(fileURLWithPath: $0) as NSURL }
                if urls.isEmpty || !pasteboard.writeObjects(urls) {
                    pasteboard.setString(item.text, forType: .string)
                }
            }
        case .text, .link, .color:
            pasteboard.setString(item.text, forType: .string)
        }
        markOwnChange()
        // Move it to the top of the history.
        var moved = item
        moved.date = Date()
        var h = history
        if h.items.contains(where: { $0.id == item.id }) {
            h.limit = AppSettings.shared.clipboardLimit
            let evicted = h.add(moved)
            history = h
            deleteImageFiles(of: evicted)
            scheduleSave()
        }
    }

    private func markOwnChange() {
        let count = pasteboard.changeCount
        ownChangeCount = count
        lastChangeCount = count
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey = CGKeyCode(9)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false) else { return }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    private static func pngData(from data: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: data) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: Files & persistence

    private func deleteImageFiles(of items: [ClipItem]) {
        let stillUsed = Set(history.items.compactMap(\.imageFile))
        let files = items.compactMap(\.imageFile).filter { !stillUsed.contains($0) }
        guard !files.isEmpty else { return }
        for file in files { imageCache.removeObject(forKey: file as NSString) }
        let dir = ClipboardService.clipsDirectory
        ioQueue.async {
            for file in files {
                try? FileManager.default.removeItem(at: dir.appendingPathComponent(file))
            }
        }
    }

    private func scheduleSave() {
        saveRequests.send(())
    }

    private func saveHistory() {
        let snapshot = history
        let url = ClipboardService.historyFile
        let dir = ClipboardService.supportDirectory
        let logger = self.logger
        ioQueue.async {
            do {
                try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
                let encoder = JSONEncoder()
                encoder.dateEncodingStrategy = .secondsSince1970
                let data = try encoder.encode(snapshot)
                try data.write(to: url, options: .atomic)
            } catch {
                logger.error("could not save clipboard history: \(error.localizedDescription, privacy: .public)")
            }
        }
    }

    private func loadHistory() {
        let url = ClipboardService.historyFile
        guard let data = try? Data(contentsOf: url) else {
            history = ClipboardHistory(limit: AppSettings.shared.clipboardLimit)
            return
        }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .secondsSince1970
        if var loaded = try? decoder.decode(ClipboardHistory.self, from: data) {
            loaded.limit = AppSettings.shared.clipboardLimit
            // Drop image items whose file disappeared.
            let dir = ClipboardService.clipsDirectory
            for item in loaded.items where item.kind == .image {
                let exists = item.imageFile.map { FileManager.default.fileExists(atPath: dir.appendingPathComponent($0).path) } ?? false
                if !exists { _ = loaded.remove(id: item.id) }
            }
            history = loaded
        } else {
            logger.error("clipboard history unreadable; starting fresh")
            history = ClipboardHistory(limit: AppSettings.shared.clipboardLimit)
        }
    }
}
